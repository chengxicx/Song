def _level_for(name, etype):
    "TOPIK band from KFL, falling back to a band by parsing type."
    if name in _KFL_GRADE:
        return _band(_KFL_GRADE[name])
    # Coarse fallback mirroring the engine: bare nouns/universal forms are
    # beginner, verb/composite forms tend to be intermediate.
    return _band(1 if etype in ("noun", "universal") else 3)


