def enrich(entries):
    for e in entries:
        name = e.get("name", "")
        zh = _ZH.get(name)
        if zh:
            e["zh"] = zh
        ko = _KO.get(name)
        if ko:
            e["ko"] = ko
        e["level"] = _level_for(name, e.get("type", ""))
    return entries


def main(argv):
    path = (
        argv[1]
        if len(argv) > 1
        else os.path.join(os.path.dirname(os.path.abspath(__file__)), "grammar_ko.json")
    )
    with open(path, encoding="utf-8") as fh:
        entries = json.load(fh)
    enrich(entries)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(entries, fh, ensure_ascii=False, indent=1)
    n_zh = sum(1 for e in entries if e.get("zh"))
    n_ko = sum(1 for e in entries if e.get("ko"))
    n_lev = sum(1 for e in entries if e.get("level"))
    print(f"enriched {len(entries)} records -> {path}")
    print(f"  with zh : {n_zh}")
    print(f"  with ko : {n_ko}")
    print(f"  with lev: {n_lev}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
