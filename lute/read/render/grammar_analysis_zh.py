_PUNCT = set("，。！？；：、（）「」『』《》〈〉" "''…—·,.!?;:\"'()`")

_HAN = r"\u4e00-\u9fff"


def _tokens_for(sentence):
    "Character-level tokens; punctuation flagged for sequence skipping."
    return [
        {
            "surface": ch,
            "pos": "PUNCT" if ch in _PUNCT or ch.isspace() else "X",
            "idx": i,
        }
        for i, ch in enumerate(sentence)
    ]


