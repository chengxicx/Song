_GARBAGE = re.compile(r"^[~〜…\s\-+/。、，]+$")


def _romaji(pattern):
    out = []
    for ch in pattern:
        cp = ord(ch)
        if 0x3041 <= cp <= 0x3096:  # hiragana
            out.append(_KANA_ROMAJI.get(ch, ""))
        elif 0x30A1 <= cp <= 0x30F6:  # katakana
            out.append(_KANA_ROMAJI.get(chr(cp - _KATA_OFFSET), ""))
        elif ch in "ー~〜":
            out.append("")
        elif ch.isascii() and ch.isalnum():
            out.append(ch.lower())
        # kanji, CJK punctuation: dropped
    return "".join(out)


def _kebab(pattern, taken):
    s = re.sub(r"[^a-z0-9]+", "-", _romaji(pattern)).strip("-")
    h = hashlib.md5(pattern.encode("utf-8")).hexdigest()[:6]
    if len(s) < 3:
        return f"mat-{h}"
    if s in taken:
        return f"{s}-{h}"
    return s


def _en_from_zh(zh):
    "Derive an English gloss from the material's Chinese meaning."
    out = zh
    for zh_frag, en in _ZH2EN:
        out = out.replace(zh_frag, en)
    out = re.sub(r"[~〜…；;，,]+", " / ", out)
    out = re.sub(r"[（）()「」『』\[\]]", " ", out)
    out = re.sub(r"\s+", " ", out).strip(" /")
    if _GARBAGE.match(out) or len(out) < 3:
        return None
    return out[:160]


def load_missing():
    path = os.path.join(MATERIALS, "audit_missing.json")
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def existing_ids():
    ids = set()
    for path in sorted(glob.glob(os.path.join(LIBRARY, "n[1-5].json"))):
        with open(path, encoding="utf-8") as fh:
            ids.update(e["id"] for e in json.load(fh))
    return ids


def build_rows(missing):
    rows, skipped, taken = collections.defaultdict(list), [], set(existing_ids())
    for pattern, meta in sorted(missing.items()):
        en = _en_from_zh(meta.get("meaning_zh") or "")
        if en is None:
            skipped.append(pattern)
            continue
        eid = _kebab(pattern, taken)
        if eid in taken:
            continue
        taken.add(eid)
        level = meta.get("level") or "N1"
        rows[level].append(
            {
                "id": eid,
                "pattern": pattern,
                "level": level,
                "meaning_en": en,
                "meaning_detailed": meta.get("meaning_zh", ""),
                "formation": meta.get("formation", ""),
                "formation_notes": [meta["notes"]] if meta.get("notes") else [],
                "formality": "neutral",
                "related": [],
                "examples": [
                    {
                        "japanese": ex["japanese"],
                        "english": "",
                        "chinese": ex["chinese"],
                    }
                    for ex in meta.get("examples", [])
                ],
            }
        )
    return rows, skipped


def zh_additions(rows):
    out = {}
    for level_entries in rows.values():
        for e in level_entries:
            zh = e["meaning_detailed"]
            out[e["id"]] = zh if 4 <= len(zh) <= 40 else zh[:40]
    return out


def append_zh(_unused=None):
    "Paste `id: gloss,` lines from zh_additions.json into the ZH dict."
    path = os.path.join(MATERIALS, "zh_additions.json")
    if not os.path.exists(path):
        print("no zh_additions.json -- run --write first")
        return 1
    with open(path, encoding="utf-8") as fh:
        zh = json.load(fh)
    with open(ZH_SCRIPT, encoding="utf-8") as fh:
        src = fh.read()
    have = set(re.findall(r'^\s{4}"([a-z0-9-]+)":', src, re.M))
    new = {k: v for k, v in zh.items() if k not in have}
    if not new:
        print("ZH dict already covers every new id")
        return 0
    lines = "".join(f'    "{k}": "{v}",\n' for k, v in sorted(new.items()))
    marker = re.search(r"^ZH = \{\n", src, re.M)
    if not marker:
        print("cannot locate ZH dict opening in", ZH_SCRIPT)
        return 1
    src = src[: marker.end()] + lines + src[marker.end() :]
    with open(ZH_SCRIPT, "w", encoding="utf-8") as fh:
        fh.write(src)
    print(
        f"generate_grammar_zh.py: +{len(new)} ZH lines "
        f"(now run `python -m scripts.generate_grammar_zh --write`)"
    )
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--append-zh", action="store_true")
    args = ap.parse_args()
    missing = load_missing()
    if not missing:
        print("no audit_missing.json yet -- run scripts.audit_grammar_coverage")
        return 1
    rows, skipped = build_rows(missing)
    zh = zh_additions(rows)
    print(
        f"new rows: {sum(len(v) for v in rows.values())} "
        f"across {', '.join(f'{k}:{len(v)}' for k, v in sorted(rows.items()))}"
    )
    print(f"skipped (no EN gloss derivable): {len(skipped)}")
    for p in skipped:
        print("  -", p)
    if args.append_zh:
        return append_zh(zh)
    if not args.write:
        print("(dry run: pass --write)")
        return 0
    for level, entries in sorted(rows.items()):
        path = os.path.join(LIBRARY, LEVEL_FILE[level])
        with open(path, encoding="utf-8") as fh:
            data = json.load(fh)
        by_id = {e["id"]: e for e in data}
        added = []
        updated = 0
        for e in entries:
            if e["id"] not in by_id:
                added.append(e)
                continue
            # A row written by an earlier run (before the audit carried
            # examples) may sit there example-less -- such rows derive no
            # matcher and never fire.  Backfill what this run's material
            # can provide; never overwrite existing content.
            row = by_id[e["id"]]
            if not row.get("examples") and e["examples"]:
                row["examples"] = e["examples"]
                updated += 1
            if not row.get("meaning_detailed") and e["meaning_detailed"]:
                row["meaning_detailed"] = e["meaning_detailed"]
                updated += 1
            if not row.get("formation") and e["formation"]:
                row["formation"] = e["formation"]
                updated += 1
        data.extend(added)
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(data, fh, ensure_ascii=False, indent=1)
        print(f"{path}: +{len(added)} rows, {updated} fields backfilled")
    with open(
        os.path.join(MATERIALS, "zh_additions.json"), "w", encoding="utf-8"
    ) as fh:
        json.dump(zh, fh, ensure_ascii=False, indent=1, sort_keys=True)
    print(
        f"zh_additions.json: {len(zh)} glosses "
        f"(regenerate zh.json via generate_grammar_zh --write)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
