"""Merge audited grammar materials into the built-in library and regenerate
the Chinese gloss file.

Two stages, both idempotent, both driven by the audit reports:

  1. merge  -- every ``audit_missing.json`` entry becomes a new row in
     ``lute/jlpt_data/grammar/n{n}.json`` for its level, keeping the
     verbatim-copy schema (kebab-case id, pattern, level, meaning_en,
     meaning_detailed, formation, formation_notes, formality, related,
     examples[{japanese, english, source}]).  ``meaning_en`` is derived
     from the material's ``meaning_zh`` through the ZH->EN gloss table
     below; entries the table cannot translate are reported and skipped,
     never guessed.  ``source`` on each example is the material name, so
     provenance stays auditable next to the jkindrix rows.  Ids are the
     romaji of the pattern's kana (あっての -> atte-no); pure-kanji or
     colliding patterns fall back to a stable hash suffix so re-runs are
     idempotent.

  2. zh     -- new ids are written to
     ``scripts/grammar_materials/zh_additions.json`` mapping id -> Chinese
     gloss taken verbatim from the material's ``meaning_zh`` (clamped to
     4..40 chars like the existing table).  ``--append-zh`` pastes those
     lines into the ZH dict of ``scripts/generate_grammar_zh.py``; the
     zh.json itself is then regenerated by that script's ``--write``,
     which stays the single source of truth.

Usage::

    python -m scripts.merge_grammar_materials             # report only
    python -m scripts.merge_grammar_materials --write     # apply both stages
    python -m scripts.merge_grammar_materials --append-zh # paste into ZH dict
"""

